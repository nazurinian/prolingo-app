import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';

const names = ['prolingo_text_library_d3b_qa_a3_source', 'prolingo_text_library_d3b_qa_a3_destination'];
export const a3Libraries = Object.fromEntries(names.map(name =>
  [name, 'prolingo_book_qa_audio_staging_v1__' + createHash('sha256').update(name).digest('hex')]));
const root = '[data-book-data-manager]';
const host = 'window.__bookQaProps("[data-book-qa-indicator]", "bookQaConnection", true).bookQaConnection';
const q = JSON.stringify;

export async function checkBookQaA3({ call, evaluate, waitFor, clickButton, navigate, chooseOptIn, probe, uatOrigin }) {
  const checks = [];
  const pass = name => { checks.push(name); console.log('PASS', name); };
  const click = async selector => {
    await waitFor(`document.querySelector(${q(selector)}) && !document.querySelector(${q(selector)}).disabled`);
    await evaluate(`document.querySelector(${q(selector)}).click(); true`);
  };
  const bookButton = async label => {
    const expression = `[...document.querySelectorAll('${root} button')].find(button => button.textContent.trim() === ${q(label)})`;
    await waitFor(`(${expression}) && !(${expression}).disabled`);
    await evaluate(`(${expression}).click(); true`);
  };
  const change = (selector, value) => evaluate(`(() => {
    const node = document.querySelector(${q(selector)});
    if (!node) throw Error('Missing field ' + ${q(selector)});
    const proto = Object.getPrototypeOf(node);
    Object.getOwnPropertyDescriptor(proto, 'value').set.call(node, ${q(value)});
    node.dispatchEvent(new Event(node.tagName === 'SELECT' ? 'change' : 'input', { bubbles: true }));
    return true;
  })()`);
  const field = (label, value) => change(`${root} [aria-label="${label}"]`, value);
  const db = name => probe(`module.readCompleteLibrary(${q(name)})`);
  const state = () => evaluate(`${host}.session.getState()`);
  const open = async (name, existing = false) => {
    await navigate(uatOrigin, '/?qa=book-qa&db=' + name);
    await waitFor(`location.search.includes(${q(name)}) && document.querySelector('[data-book-qa-host="disconnected"]')`);
    await chooseOptIn();
    await clickButton(existing ? 'Load / Connect existing v2 library' : 'Initialize empty v2 library');
    await waitFor(`Boolean(document.querySelector('[data-book-qa-indicator]'))`);
    await clickButton('Book Data');
    await waitFor(`document.querySelector('${root}')?.open`);
  };
  const settle = () => waitFor(`!${host}.session.getState().pending`);
  const newCollection = async name => {
    await click('[data-dm-nav-library]');
    await click('[data-dm-toggle-create-collection]');
    await field('New Collection title', name);
    await click('[data-dm-submit-create-collection]');
    await settle();
  };
  const newWorkspace = async (title, type) => {
    await click('[data-dm-nav-root]');
    await click('[data-dm-toggle-create-workspace]');
    await field('New Workspace title', title);
    await field('New Workspace type', type);
    await click('[data-dm-submit-create-workspace]');
    await waitFor(`${host}.session.getState().view.workspace?.document.title === ${q(title)}`);
    return (await state()).view.workspace.document;
  };
  const setFile = (selector, payload, filename, fromBase64 = false) => evaluate(`(() => {
    const transfer = new DataTransfer();
    const value = ${q(payload)};
    const bytes = ${fromBase64} ? Uint8Array.from(atob(value), item => item.charCodeAt(0)) : value;
    transfer.items.add(new File([bytes], ${q(filename)}));
    const field = document.querySelector(${q(selector)});
    field.files = transfer.files; field.dispatchEvent(new Event('change', { bubbles: true }));
    return true;
  })()`);
  const jsonField = `${root} input[type=file]`;
  const captureDownloads = () => evaluate(`(() => {
    window.a3Downloads = {};
    const nativeClick = HTMLAnchorElement.prototype.click;
    HTMLAnchorElement.prototype.click = function() {
      if (this.download && this.href.startsWith('blob:')) {
        window.a3Downloads[this.download] = fetch(this.href).then(response => response.blob());
      } else nativeClick.call(this);
    };
    return true;
  })()`);
  const getDownload = async prefix => {
    await waitFor(`Object.keys(window.a3Downloads).some(name => name.startsWith(${q(prefix)}))`);
    return await evaluate(`Object.keys(window.a3Downloads).find(name => name.startsWith(${q(prefix)}))`);
  };
  const readJson = async scope => {
    const name = await getDownload('PL_BOOK_' + scope);
    return evaluate(`window.a3Downloads[${q(name)}].then(blob => blob.text())`);
  };

  await open(names[0]);
  assert.equal((await state()).view.selection.collectionId, null);
  await newCollection('A3 Reading');
  await newCollection('A3 Empty');
  const [reading, empty] = (await db(names[0])).snapshot.collections;
  await click(`[data-dm-collection-reorder-up="${empty.id}"]`);
  await settle();
  assert.equal((await state()).view.catalog.collections[0].id, empty.id);
  const source = await newWorkspace('A3 Mixed source', 'mixed');
  const paragraph = await newWorkspace('A3 Paragraph', 'paragraph');
  const scene = await newWorkspace('A3 Conversation', 'conversation');
  await click('[data-dm-nav-root]');
  await click(`[data-dm-workspace-reorder-up="${scene.id}"]`);
  await settle();
  assert.deepEqual((await state()).view.catalog.rootDocuments.map(row => row.id), [source.id, scene.id, paragraph.id]);
  await change(`${root} input[type=search]`, 'Mixed source');
  await bookButton('A3 Mixed source · Root');
  await field('Workspace Title', 'A3 Renamed source');
  await field('Workspace Collection', reading.id);
  await click(`${root} fieldset input[type=checkbox]`);
  await change(`${root} fieldset input[required]`, 'A3 Independent Title');
  await change(`${root} fieldset input:not([required]):not([type=checkbox])`, 'Judul A3');
  await click('[data-dm-workspace-save]');
  await settle();
  assert.deepEqual((await state()).view.selection, { workspaceId: source.id, collectionId: reading.id });
  assert.equal((await state()).view.workspace.document.uid, source.uid);
  await bookButton('Library');
  await click(`[data-dm-collection="${reading.id}"]`);
  assert.equal(await evaluate(`document.querySelector('[data-dm-collection-delete="${reading.id}"]').disabled`), true);
  await click(`[data-dm-collection-edit-toggle="${reading.id}"]`);
  await field('Collection title ' + reading.id, 'A3 Archive');
  await click(`[data-dm-collection-save="${reading.id}"]`);
  await settle();
  await click(`[data-dm-collection="${empty.id}"]`);
  await click(`[data-dm-collection-delete="${empty.id}"]`);
  await bookButton('Cancel change');
  assert.equal((await db(names[0])).snapshot.collections.length, 2);
  await click(`[data-dm-collection-delete="${empty.id}"]`);
  await bookButton('Confirm change');
  await settle();
  assert.equal((await db(names[0])).snapshot.collections.length, 1);
  await bookButton('Refresh library');
  await waitFor(`[...document.querySelectorAll('${root} button')].some(button => button.textContent.trim() === 'Library' && !button.disabled)`);
  await click(`[data-dm-workspace="${source.id}"]`);
  pass('A3-A actual Root/Collection create, rename, order, nonempty guard, confirmed deletion, Workspace creation/search/order/move and Refresh');

  await bookButton('Cards, Units & Sentences');
  await field('New Card kind', 'conversation');
  assert.equal(await evaluate("document.querySelector('[data-dm-create-card-submit]').disabled"), true);
  await bookButton('Workspace & Speakers');
  await click('[data-conversation-speaker-registry] > button');
  for (const label of ['Mira', 'Andi', 'Nina']) {
    await field('New speaker label', label);
    await bookButton('Register');
    await settle();
  }
  const speaker = (await state()).view.workspace.speakers.find(s => s.label === 'Mira');
  await bookButton('Cards, Units & Sentences');
  const cards = () => evaluate(`${host}.session.getState().view.workspace.presentation.cards`);
  const newCard = async (kind, en = '', id = '') => {
    await field('New Card kind', kind);
    if (en) await field('New Card title', en);
    if (id) await change('[data-dm-create-card-form] input:not([aria-label])', id);
    const count = (await cards()).length;
    await click('[data-dm-create-card-submit]');
    await waitFor(`${host}.session.getState().view.workspace.presentation.cards.length === ${count + 1}`);
    return (await cards()).at(-1);
  };
  const p1 = await newCard('paragraph', 'A3 Chapter', 'Bab A3');
  const p2 = await newCard('paragraph');
  const c1 = await newCard('conversation');
  await click(`[data-dm-card-up="${c1.id}"]`);
  await settle();
  assert.deepEqual((await cards()).map(card => card.id), [p1.id, c1.id, p2.id]);
  const createUnit = async (cardId, en = '', id = '') => {
    await click(`[data-dm-open-create-unit="${cardId}"]`);
    if (en) await field('New Unit first text ' + cardId, en);
    if (id) await field('New Unit first meaning ' + cardId, id);
    if (cardId === c1.id) await field('New Turn speaker ' + cardId, speaker.id);
    await click(`[data-dm-create-unit-submit="${cardId}"]`);
    await settle();
  };
  await createUnit(p1.id, 'A3 authored audio sentence.', 'Kalimat audio A3.');
  await createUnit(p1.id);
  await createUnit(c1.id, 'A3 conversation line.', 'Kalimat dialog A3.');
  await createUnit(c1.id);
  const tree = (await state()).view.workspace.documentTree;
  const seg = tree.blocks.find(card => card.id === p1.id).segments[0];
  assert.deepEqual(tree.blocks.find(card => card.id === c1.id).units.map(unit => [unit.speakerId, unit.segments.length]), [[speaker.id, 1], [speaker.id, 0]]);
  await bookButton('Workspace & Speakers');
  await click('[data-conversation-speaker-registry] > button');
  await click('[aria-label="Edit speaker Mira"]');
  await field('Rename Mira', 'Miranda');
  await click('[aria-label="Save speaker name"]');
  await settle();
  assert.equal((await state()).view.workspace.speakers.find(row => row.id === speaker.id).label, 'Miranda');
  assert.equal(await evaluate("document.querySelector('[aria-label=\"Remove speaker Miranda\"]').disabled"), true);
  await click('[aria-label="Remove speaker Nina"]');
  await bookButton('Confirm change');
  await settle();
  await bookButton('Back to Reader');
  await waitFor(`document.querySelector('[data-book-main-title]')?.innerText.includes('A3 Independent Title')`);
  await click('[data-book-heading-audio] summary');
  await click('[aria-label="Read Main Title"]');
  await waitFor(`document.querySelector('[data-book-heading-status]')?.innerText.includes('saved')`);
  assert.equal(await evaluate(`document.querySelector('[data-book-main-title] [lang="id"]')?.textContent`), 'Judul A3');
  await click('[data-book-heading-audio] summary');
  pass('A3-B actual Mixed interleave, bilingual title and Heading, empty Card/Section/Turn, Scene threshold, Speaker rename/removal and independent Read');

  const requests = await probe(`module.seedA3Audio(${host}, ${q(source.id)})`);
  const sourceReads = await probe(`module.readA3Audio(${host}, ${q(source.id)})`);
  assert(sourceReads.every(item => item.status === 'ready' && item.digest?.length === 64));
  assert.equal(sourceReads.at(-1).trustedComposition, true);
  await clickButton('Book Data');
  await bookButton('Cards, Units & Sentences');
  await field('Sentence meaning ' + seg.id, 'Arti baru tanpa mengubah EN.');
  await click(`[data-dm-segment-save="${seg.id}"]`);
  await settle();
  const afterEdit = await probe(`module.readA3Audio(${host}, ${q(source.id)}, ${q(requests)})`);
  assert.equal(afterEdit[1].status, 'stale');
  assert.deepEqual(afterEdit.filter((_, index) => index !== 1), sourceReads.filter((_, index) => index !== 1));
  await field('Sentence meaning ' + seg.id, seg.meaning);
  await click(`[data-dm-segment-save="${seg.id}"]`);
  await settle();
  assert.deepEqual(await probe(`module.readA3Audio(${host}, ${q(source.id)})`), sourceReads);
  pass('A3-B ID edit stales only its binding; restoring ID text recovers the original bytes and alternate EN profile');

  await captureDownloads();
  await bookButton('JSON Transfer');
  await bookButton('Export Workspace JSON');
  await bookButton('Export Custom Collection JSON');
  await bookButton('Export Root JSON');
  await bookButton('Export Full Library JSON');
  const workspaceJson = await readJson('WORKSPACE');
  const collectionJson = await readJson('COLLECTION');
  const rootJson = JSON.parse(await readJson('ROOT'));
  const libraryJson = JSON.parse(await readJson('LIBRARY'));
  assert.equal(JSON.parse(workspaceJson).audioBinaryIncluded, false);
  assert.deepEqual(rootJson.packs.map(pack => pack.documents[0].title), ['A3 Conversation', 'A3 Paragraph']);
  assert.deepEqual(libraryJson.packs.map(pack => pack.scope.type), ['document', 'document', 'collection']);
  await bookButton('Back to Reader');
  await click('[data-book-portable-audio] summary');
  await clickButton('Export Portable Audio');
  const zipName = await getDownload('PL_PORTABLE__');
  const zip = await probe(`module.inspectA3Zip(await window.a3Downloads[${q(zipName)}])`);
  assert.equal(zip.version, 3);
  assert.equal(zip.references, sourceReads.length);
  assert(zip.paths.includes('AUDIO_INDEX.csv'));
  assert(sourceReads.every(row => zip.digests[row.fingerprint] === row.digest));
  const zipBytes = await evaluate(`window.a3Downloads[${q(zipName)}].then(async blob => btoa(Array.from(new Uint8Array(await blob.arrayBuffer()), value => String.fromCharCode(value)).join('')))`);
  const sourcePersisted = (await db(names[0])).snapshot;
  pass('A3-C actual Workspace, Collection, Root and Library JSON downloads, and Portable v3 archive with matching asset bytes');

  await open(names[1]);
  const decoy = await newWorkspace('A3 Decoy', 'paragraph');
  assert.equal(decoy.id, source.id);
  await bookButton('JSON Transfer');
  await setFile(jsonField, '{invalid', 'bad.json');
  await waitFor(`Boolean(document.querySelector('${root} form ~ [role=alert]'))`);
  await setFile(jsonField, workspaceJson, 'workspace.json');
  await waitFor(`Boolean(document.querySelector('[data-book-json-preview]'))`);
  await bookButton('Cancel import');
  assert.equal((await db(names[1])).snapshot.documents.length, 1);
  await setFile(jsonField, workspaceJson, 'workspace.json');
  await waitFor(`Boolean(document.querySelector('[data-book-json-preview]'))`);
  const external = await probe(`module.executeExternal(${q(names[1])}, {}, { type: 'collection.create', payload: { title: 'External writer' } })`);
  assert.equal(external.ok, true);
  await bookButton('Import as new copy');
  await waitFor(`Boolean(document.querySelector('[data-book-data-error="STALE_RESULT"]'))`);
  assert.equal((await db(names[1])).snapshot.documents.length, 1);
  await bookButton('Refresh library');
  await waitFor(`!document.querySelector('[data-book-data-error]')`);
  await setFile(jsonField, workspaceJson, 'workspace.json');
  await waitFor(`Boolean(document.querySelector('[data-book-json-preview]'))`);
  await change(`${root} form select`, 'new');
  await change(`${root} form input[required]`, 'A3 New destination');
  await bookButton('Import as new copy');
  await waitFor(`${host}.session.getState().view.workspace?.document.title === 'A3 Renamed source'`);
  const copy = (await state()).view.workspace.document;
  assert.notEqual(copy.id, source.id);
  assert.notEqual(copy.uid, source.uid);
  assert.equal(copy.metadata.prolingoTextPackSource.sourceUid, source.uid);
  assert.equal((await state()).view.catalog.collections.find(row => row.id === copy.collectionId).title, 'A3 New destination');
  const beforeAudio = await probe(`module.readA3Audio(${host}, ${q(copy.id)})`);
  assert(beforeAudio.every(row => row.status !== 'ready' && row.digest === null));
  await bookButton('Back to Reader');
  await click('[data-book-portable-audio] summary');
  await setFile('[data-book-portable-audio] input[type=file]', zipBytes, zipName, true);
  await clickButton('Import selected files');
  await waitFor(`document.querySelector('[data-book-portable-status]')?.innerText.includes('${sourceReads.length} references committed')`);
  const copyReads = await probe(`module.readA3Audio(${host}, ${q(copy.id)})`);
  assert.deepEqual(copyReads, sourceReads.map(row => ({ ...row, trustedComposition: false })));
  await clickButton('Import selected files');
  await waitFor(`document.querySelector('[data-book-portable-status]')?.innerText.includes('0 references committed and ${sourceReads.length} already available')`);
  pass('A3-C cancellation, malformed JSON, real stale transaction, atomic new destination, remapped UID lineage and idempotent Portable restore');

  await open(names[1], true);
  await bookButton('JSON Transfer');
  await setFile(jsonField, collectionJson, 'collection.json');
  await waitFor(`Boolean(document.querySelector('[data-book-json-preview]'))`);
  await bookButton('Import as new copy');
  await waitFor(`document.querySelector('${root}')?.innerText.includes('Imported 1 Workspace copies and 1 new Collections')`);
  await setFile(jsonField, collectionJson, 'collection.json');
  await waitFor(`Boolean(document.querySelector('[data-book-json-preview]'))`);
  await change(`${root} form select`, copy.collectionId);
  await bookButton('Import as new copy');
  await waitFor(`document.querySelector('${root}')?.innerText.includes('Imported 1 Workspace copies and 0 new Collections')`);
  assert.deepEqual((await state()).view.catalog.collections.find(item => item.id === copy.collectionId).documents.map(doc => doc.title), ['A3 Renamed source', 'A3 Renamed source']);
  assert.equal((await state()).view.catalog.collections.find(item => item.title === 'A3 Archive').documents.length, 1);
  const restore = async (json, filename, expected) => {
    await setFile(jsonField, json, filename);
    await waitFor(`Boolean(document.querySelector('[data-book-json-preview]'))`);
    await bookButton('Import as new copy');
    await waitFor(`document.querySelector('${root}')?.innerText.includes(${q(expected)})`);
  };
  await restore(workspaceJson, 'workspace.json', 'Imported 1 Workspace copies and 0 new Collections');
  assert.equal((await state()).view.workspace.document.collectionId, null);
  const rootCopy = (await state()).view.workspace.document;
  await bookButton('Workspace & Speakers');
  await click(`[data-dm-workspace-delete="${rootCopy.id}"]`);
  await bookButton('Cancel change');
  assert((await state()).view.workspace.document.id === rootCopy.id);
  await click(`[data-dm-workspace-delete="${rootCopy.id}"]`);
  await bookButton('Confirm change');
  await settle();
  assert.equal((await state()).view.selection.collectionId, null);
  await bookButton('JSON Transfer');
  await restore(q(libraryJson), 'library.json', 'Imported 3 Workspace copies and 1 new Collections');
  assert.equal((await state()).view.catalog.collections.filter(item => item.title === 'A3 Archive').length, 2);
  assert((await state()).view.catalog.rootDocuments.some(doc => doc.title === 'A3 Paragraph'));
  await call('Emulation.setDeviceMetricsOverride', { width: 390, height: 844, deviceScaleFactor: 1, mobile: true });
  await waitFor(`document.querySelector('${root}').clientWidth < 390 && document.querySelector('${root}').scrollWidth <= document.querySelector('${root}').clientWidth + 1`);
  await bookButton('Library');
  await bookButton('Workspace & Speakers');
  await bookButton('Cards, Units & Sentences');
  await bookButton('Back to Reader');
  await clickButton('Book Data');
  await waitFor(`document.querySelector('${root}')?.open`);
  await call('Emulation.setDeviceMetricsOverride', { width: 1440, height: 920, deviceScaleFactor: 1, mobile: false });
  await open(names[0], true);
  assert.deepEqual((await db(names[0])).snapshot, sourcePersisted);
  pass('A3-C Root, Collection preservation/explicit destination and full Library recovery. A3-A confirmed Workspace delete, mobile and isolated reconnect');
  return { checks, zipName, zip, source: { id: source.id, uid: source.uid }, copy: { id: copy.id, uid: copy.uid },
    json: { workspace: JSON.parse(workspaceJson).packageType, collection: JSON.parse(collectionJson).packageType,
      root: rootJson.packs.length, library: libraryJson.packs.length },
    beforeAudio: beforeAudio.map(row => row.status), sourceAudio: sourceReads, afterAudio: copyReads };
}
