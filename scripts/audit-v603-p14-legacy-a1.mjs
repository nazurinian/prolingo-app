import assert from 'node:assert/strict';
import { createLegacyTextMigrationPlan, createTextAudioVariantRecord } from '../src/domain/text/textLibraryDomain.js';
import { selectTextLegacyManagement, inspectTextLegacyManagement } from '../src/domain/text/textLegacyManagementDomain.js';
import { backfillTextContentUnits } from '../src/domain/text/textContentUnitDomain.js';
import { backfillTextGlobalUids } from '../src/domain/text/textGlobalIdentityDomain.js';
let calls = 0;
globalThis.indexedDB = new Proxy({}, { get() { calls++; throw Error('Forbidden'); } });
globalThis.localStorage = new Proxy({}, { get() { calls++; throw Error('Forbidden'); } });
const source = createLegacyTextMigrationPlan({ items: [{ id: 'TEXT_000011', text: 'Same line.' }, { id: 'TEXT_000012', text: 'Same line.' }], highWater: 20 });
const snapshot = { ...source, initialized: true, audioVariants: [createTextAudioVariantRecord({ id: 'TXTAUDIO_000001', segmentId: source.segments[0].id, metadata: { opaqueAudio: true } })] };
snapshot.counters.audioVariant = 1;
const before = JSON.stringify(snapshot), documentId = snapshot.documents[0].id, view = selectTextLegacyManagement(snapshot, { documentId });
assert.deepEqual(view.workspace.lines.map(l => l.id), ['TEXT_000011', 'TEXT_000012']);
assert.notEqual(view.workspace.lines[0].segment.id, view.workspace.lines[1].segment.id);
assert.equal(view.workspace.lines[0].segment.audioVariants[0].id, 'TXTAUDIO_000001');
assert.equal(view.workspace.lines[0].audioReadiness, 'not-evaluated');
assert.ok(Object.isFrozen(view.workspace.lines[0].segment.metadata));
assert.ok(Object.values(view.capabilities).every(v => v === false));
assert.equal(JSON.stringify(snapshot), before);
const v2 = backfillTextContentUnits(backfillTextGlobalUids(snapshot).snapshot).snapshot;
assert.equal(v2.contentUnits.length, 0);
assert.equal(selectTextLegacyManagement(v2, { documentId }).workspace.lines.length, 2);
const bad = structuredClone(snapshot); bad.segments.push({ ...bad.segments[0], id: 'SEGMENT_000099', uid: undefined, order: 2 });
assert.equal(inspectTextLegacyManagement(bad, { documentId }).status, 'unavailable');
assert.equal(inspectTextLegacyManagement(snapshot, { documentId: 'foreign' }).error.code, 'UNSUPPORTED_WORKSPACE');
assert.equal(calls, 0);
console.log('PASS P14 A1: native Legacy identity/duplicate text/one-Segment cardinality, logical audio, v2 isolation, frozen projection, zero storage calls');
